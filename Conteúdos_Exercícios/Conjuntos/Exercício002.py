conj1 = {1, 2, 3, 4}
conj2 = {3, 4, 5, 6}
print(f'Conjunto 1: {conj1}')
print(f'Conjunto 2: {conj2}')

print(f'União entre conjuntos 1 e 2: {conj1.union(conj2)}')
print(f'Intersecção entre conjuntos 1 e 2: {conj1.intersection(conj2)}')
print(f'Diferença entre conjuntos 1 e 2 {conj1.difference(conj2)}')